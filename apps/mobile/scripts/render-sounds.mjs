/**
 * `pnpm --filter @kakure/mobile sounds`: renders @kakure/sounds' cue definitions to WAV for the phone
 * (Senryo's pattern, senryo.md §6.5: the same definitions the web synthesises live, rendered offline here),
 * and writes src/feedback/generated/cue-sources.ts, the static `require` map Metro needs.
 *
 * The envelope matches packages/sounds/src/engine.ts: an exponential attack from silence to the voice's peak,
 * an exponential release back to silence at the voice's end, and an exponential pitch glide when `toHz` is set.
 * The master gain is baked in, so every player plays at volume 1. The profit cue is rendered once per
 * pentatonic ladder step. Mono, 44.1 kHz, 16-bit PCM. The output is committed.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CUES, LADDER_SEMITONES, MASTER_GAIN, SEMITONES_PER_OCTAVE, SILENT_GAIN } from "@kakure/sounds/cues";

const RATE = 44_100;
const MS_PER_S = 1000;
const PCM_MAX = 32_767;
const TAIL_MS = 20;
const OUT = new URL("../assets/sounds/", import.meta.url);
const SOURCES = new URL("../src/feedback/generated/cue-sources.ts", import.meta.url);

/** Deterministic noise, so a re-render produces the same files. */
function noiseSource(seed) {
  let state = seed >>> 0 || 1;
  return () => {
    state ^= state << 13;
    state ^= state >>> 17;
    state ^= state << 5;
    return ((state >>> 0) / 0xffffffff) * 2 - 1;
  };
}

function wave(kind, phase) {
  const cycle = phase - Math.floor(phase);
  switch (kind) {
    case "sine":
      return Math.sin(2 * Math.PI * cycle);
    case "triangle":
      return 1 - 4 * Math.abs(cycle - 0.5);
    case "square":
      return cycle < 0.5 ? 1 : -1;
    case "sawtooth":
      return 2 * cycle - 1;
    default:
      return 0;
  }
}

/** Exponential ramp between two positive values, as Web Audio's exponentialRampToValueAtTime. */
function expRamp(from, to, t) {
  return from * (to / from) ** Math.min(1, Math.max(0, t));
}

function render(cue, transpose) {
  const lengthMs = Math.max(...cue.voices.map((voice) => (voice.atMs ?? 0) + voice.ms)) + TAIL_MS;
  const samples = new Float64Array(Math.ceil((lengthMs / MS_PER_S) * RATE));
  cue.voices.forEach((voice, index) => {
    const start = Math.round(((voice.atMs ?? 0) / MS_PER_S) * RATE);
    const total = Math.round((voice.ms / MS_PER_S) * RATE);
    const attack = Math.max(1, Math.round((voice.attackMs / MS_PER_S) * RATE));
    const peak = Math.max(SILENT_GAIN, voice.gain * cue.mix);
    const noise = noiseSource(index + 1);
    let phase = 0;
    for (let i = 0; i < total && start + i < samples.length; i += 1) {
      const gain =
        i < attack
          ? expRamp(SILENT_GAIN, peak, i / attack)
          : expRamp(peak, SILENT_GAIN, (i - attack) / (total - attack));
      const hz = voice.toHz ? expRamp(voice.hz * transpose, voice.toHz * transpose, i / total) : voice.hz * transpose;
      phase += hz / RATE;
      const value = voice.wave === "noise" ? noise() : wave(voice.wave, phase);
      samples[start + i] += value * gain * MASTER_GAIN;
    }
  });
  return samples;
}

function wav(samples) {
  const bytes = samples.length * 2;
  const buffer = Buffer.alloc(44 + bytes);
  buffer.write("RIFF", 0);
  buffer.writeUInt32LE(36 + bytes, 4);
  buffer.write("WAVE", 8);
  buffer.write("fmt ", 12);
  buffer.writeUInt32LE(16, 16);
  buffer.writeUInt16LE(1, 20); // PCM
  buffer.writeUInt16LE(1, 22); // mono
  buffer.writeUInt32LE(RATE, 24);
  buffer.writeUInt32LE(RATE * 2, 28);
  buffer.writeUInt16LE(2, 32);
  buffer.writeUInt16LE(16, 34);
  buffer.write("data", 36);
  buffer.writeUInt32LE(bytes, 40);
  samples.forEach((value, index) => {
    const clipped = Math.max(-1, Math.min(1, value));
    buffer.writeInt16LE(Math.round(clipped * PCM_MAX), 44 + index * 2);
  });
  return buffer;
}

mkdirSync(OUT, { recursive: true });
const entries = [];
for (const [name, cue] of Object.entries(CUES)) {
  const steps = name === "profit" ? LADDER_SEMITONES : [0];
  steps.forEach((semitones, step) => {
    const file = steps.length > 1 ? `${name}-${step}.wav` : `${name}.wav`;
    writeFileSync(new URL(file, OUT), wav(render(cue, 2 ** (semitones / SEMITONES_PER_OCTAVE))));
    entries.push({ key: steps.length > 1 ? `${name}-${step}` : name, file });
  });
}

const lines = entries.map(({ key, file }) => `  "${key}": require("../../../assets/sounds/${file}"),`);
writeFileSync(
  SOURCES,
  `// Generated by scripts/render-sounds.mjs from @kakure/sounds. Do not edit.\n` +
    `export const CUE_SOURCES = {\n${lines.join("\n")}\n} as const;\n\n` +
    `export type CueSourceKey = keyof typeof CUE_SOURCES;\n`,
);
console.log(`rendered ${entries.length} cues into ${fileURLToPath(OUT)}`);
