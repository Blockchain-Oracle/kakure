/**
 * `pnpm --filter @kakure/mobile marks`: copies the real asset marks the web app vendors (apps/web/public/marks,
 * made by apps/web/scripts/marks.mjs from @web3icons/core and simple-icons) into a TS map of SVG markup, so the
 * phone draws the same logos with react-native-svg and never fetches one. The output is committed.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const SOURCE = new URL("../../web/public/marks/", import.meta.url);
const OUT = new URL("../src/markets/generated/marks.ts", import.meta.url);

const entries = readdirSync(SOURCE)
  .filter((file) => file.endsWith(".svg"))
  .sort()
  .map((file) => {
    const svg = readFileSync(new URL(file, SOURCE), "utf8")
      .replace(/<title>[^<]*<\/title>/, "")
      .trim();
    return `  ${JSON.stringify(file.replace(/\.svg$/, ""))}: ${JSON.stringify(svg)},`;
  });

writeFileSync(
  OUT,
  `// Generated by scripts/marks.mjs from apps/web/public/marks. Do not edit.\nexport const MARKS = {\n${entries.join("\n")}\n} as const;\n`,
);
console.log(`wrote ${entries.length} marks`);
