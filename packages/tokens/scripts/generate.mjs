/**
 * tokens.json → generated/{tokens.css, theme.css, tokens.ts, native.ts}.
 *
 * - tokens.css: CSS custom properties. Light mainnet on :root, `.dark` on <html>, and the testnet layers as
 *   `[data-network="testnet"]` (only the keys they change), so mode × network gives the four themes.
 * - theme.css: the Tailwind v4 `@theme inline` map from utilities to those properties.
 * - tokens.ts: every value for TypeScript (web), themes resolved.
 * - native.ts: the same values shaped for React Native (camelCase colours, TextStyle-like roles, Reanimated springs).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { camel, layerKeys, readTokens, resolveThemes, springToCss, THEME_NAMES, withoutMeta } from "./lib.mjs";

const OUT = new URL("../generated/", import.meta.url);
const HEADER = "Generated by packages/tokens/scripts/generate.mjs from tokens.json. Do not edit.";

const tokens = readTokens();
const themes = resolveThemes(tokens);
const springs = Object.fromEntries(
  Object.entries(withoutMeta(tokens.motion.springs)).map(([name, spring]) => [
    name,
    { ...spring, css: springToCss(spring) },
  ]),
);

const SELECTORS = {
  light: ":root",
  dark: ":root.dark",
  "testnet-light": ':root[data-network="testnet"]',
  "testnet-dark": ':root.dark[data-network="testnet"]',
};

const ROOT_FONT_PX = 16;
const px = (value) => `${value}px`;
const ms = (value) => `${value}ms`;
const bezier = (points) => `cubic-bezier(${points.join(", ")})`;
const shadowCss = ({ x, y, blur, spread, color }) => `${px(x)} ${px(y)} ${px(blur)} ${px(spread)} ${color}`;
const fontStack = (families) => families.map((family) => (family.includes(" ") ? `"${family}"` : family)).join(", ");

/** `declarations` become custom properties; `properties` are written as real CSS properties. */
function block(selector, declarations, properties = []) {
  const lines = [
    ...properties.map(([name, value]) => `  ${name}: ${value};`),
    ...declarations.map(([name, value]) => `  --${name}: ${value};`),
  ];
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

function scaleDeclarations() {
  const out = [];
  for (const [name, value] of Object.entries(withoutMeta(tokens.radius))) out.push([`radius-${name}`, px(value)]);
  for (const [name, value] of Object.entries(withoutMeta(tokens.space))) out.push([`space-${name}`, px(value)]);
  for (const [name, value] of Object.entries(withoutMeta(tokens.size))) out.push([`size-${name}`, px(value)]);
  for (const [name, value] of Object.entries(withoutMeta(tokens.layout))) out.push([`layout-${name}`, px(value)]);
  for (const [name, value] of Object.entries(withoutMeta(tokens.shadow)))
    out.push([`shadow-${name}`, shadowCss(value)]);
  for (const [name, value] of Object.entries(withoutMeta(tokens.opacity))) out.push([`opacity-${name}`, String(value)]);
  for (const [name, value] of Object.entries(withoutMeta(tokens.motion.durations)))
    out.push([`duration-${name}`, ms(value)]);
  for (const [name, value] of Object.entries(withoutMeta(tokens.motion.scales)))
    out.push([`scale-${name}`, String(value)]);
  for (const [name, value] of Object.entries(withoutMeta(tokens.motion.distances)))
    out.push([`distance-${name}`, px(value)]);
  for (const [name, value] of Object.entries(withoutMeta(tokens.motion.curves)))
    out.push([`ease-${name}`, bezier(value)]);
  for (const [name, spring] of Object.entries(springs)) {
    out.push([`spring-${name}`, spring.css.easing]);
    out.push([`spring-${name}-duration`, ms(spring.css.durationMs)]);
  }
  out.push(["font-family-sans", fontStack(tokens.type.families.sans)]);
  out.push(["font-family-display", fontStack(tokens.type.families.display)]);
  return out;
}

function tokensCss() {
  let css = `/* ${HEADER} */\n`;
  css += block(SELECTORS.light, [...Object.entries(themes.light), ...scaleDeclarations()], [["color-scheme", "light"]]);
  css += block(SELECTORS.dark, Object.entries(themes.dark), [["color-scheme", "dark"]]);
  for (const name of ["testnet-light", "testnet-dark"]) {
    css += block(
      SELECTORS[name],
      layerKeys(tokens, name).map((key) => [key, themes[name][key]]),
    );
  }
  return css;
}

function themeCss() {
  const lines = [];
  for (const name of Object.keys(themes.light)) lines.push(`--color-${name}: var(--${name});`);
  lines.push("--font-sans: var(--kakure-font-sans, var(--font-family-sans));");
  lines.push("--font-display: var(--kakure-font-display, var(--font-family-display));");
  // Static scales are written as values: a `--radius-x: var(--radius-x)` self-reference would be a cycle.
  for (const [name, value] of Object.entries(withoutMeta(tokens.radius))) lines.push(`--radius-${name}: ${px(value)};`);
  for (const [name, value] of Object.entries(withoutMeta(tokens.shadow)))
    lines.push(`--shadow-${name}: ${shadowCss(value)};`);
  for (const [name, value] of Object.entries(withoutMeta(tokens.motion.curves)))
    lines.push(`--ease-${name}: ${bezier(value)};`);
  for (const name of Object.keys(springs)) lines.push(`--ease-spring-${name}: var(--spring-${name});`);
  // In rem like Tailwind's own breakpoints, so variants sort correctly against md/lg/xl.
  for (const [name, value] of Object.entries(withoutMeta(tokens.breakpoints)))
    lines.push(`--breakpoint-${name}: ${value / ROOT_FONT_PX}rem;`);
  for (const [name, role] of Object.entries(tokens.type.roles)) {
    const tracking = role.tracking ?? (role.font === "display" ? tokens.type.displayTracking : 0);
    lines.push(`--text-${name}: ${px(role.size)};`);
    lines.push(`--text-${name}--line-height: ${px(role.lineHeight)};`);
    lines.push(`--text-${name}--font-weight: ${role.weight};`);
    lines.push(`--text-${name}--letter-spacing: ${tracking}em;`);
  }
  return `/* ${HEADER} */\n@theme inline {\n${lines.map((line) => `  ${line}`).join("\n")}\n}\n`;
}

function typeRoles() {
  return Object.fromEntries(
    Object.entries(tokens.type.roles).map(([name, role]) => [
      camel(name),
      { ...role, tracking: role.tracking ?? (role.font === "display" ? tokens.type.displayTracking : 0) },
    ]),
  );
}

function camelKeys(object) {
  return Object.fromEntries(Object.entries(withoutMeta(object)).map(([key, value]) => [camel(key), value]));
}

function webTs() {
  const data = {
    defaultMode: tokens.defaultMode,
    defaultNetwork: tokens.defaultNetwork,
    themeNames: THEME_NAMES,
    themes,
    type: { families: tokens.type.families, roles: typeRoles(), dynamicTypeCaps: tokens.type.dynamicTypeCaps },
    radius: camelKeys(tokens.radius),
    space: camelKeys(tokens.space),
    size: camelKeys(tokens.size),
    layout: camelKeys(tokens.layout),
    breakpoints: camelKeys(tokens.breakpoints),
    shadow: camelKeys(tokens.shadow),
    opacity: camelKeys(tokens.opacity),
    motion: {
      durations: camelKeys(tokens.motion.durations),
      scales: camelKeys(tokens.motion.scales),
      distances: camelKeys(tokens.motion.distances),
      curves: camelKeys(tokens.motion.curves),
      springs: Object.fromEntries(
        Object.entries(springs).map(([name, spring]) => [
          camel(name),
          {
            stiffness: spring.stiffness,
            damping: spring.damping,
            mass: spring.mass,
            overshoot: spring.overshoot,
            durationMs: spring.css.durationMs,
          },
        ]),
      ),
    },
  };
  return `// ${HEADER}\nexport const tokens = ${JSON.stringify(data, null, 2)} as const;\n\nexport type Tokens = typeof tokens;\nexport type ThemeName = (typeof tokens.themeNames)[number];\nexport type ColorToken = keyof typeof tokens.themes.light;\n`;
}

const NATIVE_FONT = { sans: "Inter", display: "RobotoCondensed" };

function nativeTs() {
  const nativeThemes = Object.fromEntries(THEME_NAMES.map((name) => [camel(name), camelKeys(themes[name])]));
  const text = Object.fromEntries(
    Object.entries(tokens.type.roles).map(([name, role]) => {
      const tracking = role.tracking ?? (role.font === "display" ? tokens.type.displayTracking : 0);
      const style = {
        fontFamily: NATIVE_FONT[role.font],
        fontSize: role.size,
        lineHeight: role.lineHeight,
        fontWeight: String(role.weight),
        letterSpacing: Number((tracking * role.size).toFixed(2)),
        ...(role.numeric ? { fontVariant: ["tabular-nums", "lining-nums"] } : {}),
      };
      return [camel(name), style];
    }),
  );
  const shadows = Object.fromEntries(
    Object.entries(withoutMeta(tokens.shadow)).map(([name, shadow]) => [camel(name), { boxShadow: shadowCss(shadow) }]),
  );
  const nativeSprings = Object.fromEntries(
    Object.entries(springs).map(([name, spring]) => [
      camel(name),
      {
        stiffness: spring.stiffness,
        damping: spring.damping,
        mass: spring.mass,
        overshootClamping: !spring.overshoot,
        energyThreshold: 6e-9,
      },
    ]),
  );
  const data = {
    defaultMode: tokens.defaultMode,
    defaultNetwork: tokens.defaultNetwork,
    themes: nativeThemes,
    text,
    radius: camelKeys(tokens.radius),
    space: camelKeys(tokens.space),
    size: camelKeys(tokens.size),
    layout: camelKeys(tokens.layout),
    shadow: shadows,
    opacity: camelKeys(tokens.opacity),
    durations: camelKeys(tokens.motion.durations),
    scales: camelKeys(tokens.motion.scales),
    curves: camelKeys(tokens.motion.curves),
    springs: nativeSprings,
    dynamicTypeCaps: tokens.type.dynamicTypeCaps,
  };
  return `// ${HEADER}\n// React Native values: numbers in points, weights as strings, springs for Reanimated's withSpring.\nexport const native = ${JSON.stringify(data, null, 2)} as const;\n\nexport type NativeTokens = typeof native;\nexport type NativeThemeName = keyof typeof native.themes;\n`;
}

mkdirSync(OUT, { recursive: true });
const files = {
  "tokens.css": tokensCss(),
  "theme.css": themeCss(),
  "tokens.ts": webTs(),
  "native.ts": nativeTs(),
};
for (const [name, content] of Object.entries(files)) {
  writeFileSync(new URL(name, OUT), content);
}
console.log(
  `tokens: wrote ${Object.keys(files).join(", ")} (${THEME_NAMES.length} themes, ${Object.keys(springs).length} springs)`,
);
